/**
 * Format and cache the source example for a component.
 * @param name
 * @returns
 */
async function formattedExample(name) {
    if (!exampleCache.has(name)) {
        exampleCache.set(name, format(exampleSource(name)));
    }

    return exampleCache.get(name);
}

